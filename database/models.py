"""
SQLAlchemy ORM models for nTrade AI database schema.

Models represent the database tables and their relationships.
All models inherit from Base which is used for migrations and table creation.

Current schema includes models for:
- Historical and live price data (OHLCV)
- Trading signals generated by analysis engine
- Executed trades and their outcomes
- Performance metrics and statistics
"""

from datetime import datetime
from typing import Optional

from sqlalchemy import (
    Column, Integer, Float, String, DateTime, Boolean, 
    Enum, ForeignKey, Index, UniqueConstraint
)
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship


# Base class for all ORM models
Base = declarative_base()


class PriceData(Base):
    """
    Historical and live market price data (OHLCV).
    
    Stores candlestick data for backtesting and live analysis.
    One record per candle per symbol per timeframe.
    """
    __tablename__ = "price_data"

    id = Column(Integer, primary_key=True, index=True)
    
    # Identification
    symbol = Column(String(20), nullable=False, index=True)  # e.g., "XAUUSD"
    timeframe = Column(Integer, nullable=False)  # Minutes (60=1h, 240=4h, etc.)
    
    # Timestamp
    timestamp = Column(DateTime, nullable=False, index=True)
    date_created = Column(DateTime, default=datetime.utcnow)
    date_modified = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    # OHLCV Data
    open = Column(Float, nullable=False)
    high = Column(Float, nullable=False)
    low = Column(Float, nullable=False)
    close = Column(Float, nullable=False)
    volume = Column(Float, nullable=False, default=0.0)
    
    # Metadata
    is_closed = Column(Boolean, default=False)  # True if candle is complete
    is_synthetic = Column(Boolean, default=False)  # True if simulated data
    
    # Indices for efficient querying
    __table_args__ = (
        UniqueConstraint('symbol', 'timeframe', 'timestamp', name='uq_price_symbol_tf_ts'),
        Index('idx_price_symbol_ts', 'symbol', 'timestamp'),
        Index('idx_price_timeframe', 'timeframe'),
    )

    def __repr__(self) -> str:
        return (
            f"PriceData(symbol='{self.symbol}', timeframe={self.timeframe}, "
            f"close={self.close}, time={self.timestamp})"
        )


class Signal(Base):
    """
    Trading signals generated by the analysis engine.
    
    Represents a buy/sell signal with complete trade setup:
    entry price, stop loss, take profit, position size, confidence score.
    """
    __tablename__ = "signals"

    id = Column(Integer, primary_key=True, index=True)
    
    # Signal identification
    symbol = Column(String(20), nullable=False, index=True)
    signal_type = Column(String(10), nullable=False)  # 'BUY' or 'SELL'
    timestamp = Column(DateTime, nullable=False, index=True, default=datetime.utcnow)
    
    # Trade Setup
    entry_price = Column(Float, nullable=False)
    stop_loss = Column(Float, nullable=False)
    take_profit = Column(Float, nullable=False)
    position_size = Column(Float, nullable=False)  # Lots or units
    
    # Risk & Reward
    risk_amount = Column(Float, nullable=False)  # Absolute risk in account currency
    reward_amount = Column(Float, nullable=False)  # Potential reward
    risk_reward_ratio = Column(Float, nullable=False)  # Reward / Risk
    
    # Model & Analysis
    confidence_score = Column(Float, nullable=False)  # 0.0 to 1.0
    model_version = Column(String(20), nullable=False)  # e.g., "RandomForest_v1"
    reasoning = Column(String(1000), nullable=True)  # Why this signal was generated
    
    # Status
    is_active = Column(Boolean, default=True)  # True until trade closes
    is_manual = Column(Boolean, default=False)  # True if manually approved
    date_created = Column(DateTime, default=datetime.utcnow)
    
    # Relationship
    trade = relationship("Trade", back_populates="signal", uselist=False)
    
    # Indices
    __table_args__ = (
        Index('idx_signal_symbol_type', 'symbol', 'signal_type'),
        Index('idx_signal_active', 'is_active'),
    )

    def __repr__(self) -> str:
        return (
            f"Signal(type={self.signal_type}, symbol='{self.symbol}', "
            f"entry={self.entry_price}, confidence={self.confidence_score:.2%})"
        )


class Trade(Base):
    """
    Executed trades and their outcomes.
    
    Records actual trades placed in the market, with entry/exit prices,
    profit/loss, and execution details.
    """
    __tablename__ = "trades"

    id = Column(Integer, primary_key=True, index=True)
    signal_id = Column(Integer, ForeignKey("signals.id"), nullable=True, index=True)
    
    # Trade identification
    symbol = Column(String(20), nullable=False, index=True)
    trade_type = Column(String(10), nullable=False)  # 'BUY' or 'SELL'
    
    # Entry
    entry_time = Column(DateTime, nullable=False)
    entry_price = Column(Float, nullable=False)
    position_size = Column(Float, nullable=False)
    
    # Exit
    exit_time = Column(DateTime, nullable=True)
    exit_price = Column(Float, nullable=True)
    exit_reason = Column(String(50), nullable=True)  # 'TP', 'SL', 'MANUAL', etc.
    
    # Risk Management
    stop_loss = Column(Float, nullable=False)
    take_profit = Column(Float, nullable=False)
    max_drawdown = Column(Float, nullable=True)  # Max loss during trade
    
    # Outcome
    profit_loss = Column(Float, nullable=True)  # P&L in account currency
    profit_loss_pips = Column(Float, nullable=True)  # P&L in pips (forex only)
    profit_loss_percent = Column(Float, nullable=True)  # P&L as % of risk
    
    # Status
    status = Column(String(20), nullable=False)  # 'OPEN', 'CLOSED', 'CANCELLED'
    
    # Metadata
    date_created = Column(DateTime, default=datetime.utcnow)
    date_modified = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    notes = Column(String(500), nullable=True)
    
    # Relationship
    signal = relationship("Signal", back_populates="trade")
    
    # Indices
    __table_args__ = (
        Index('idx_trade_symbol_status', 'symbol', 'status'),
        Index('idx_trade_entry_time', 'entry_time'),
    )

    def __repr__(self) -> str:
        pnl_str = f"{self.profit_loss:.2f}" if self.profit_loss else "OPEN"
        return (
            f"Trade(type={self.trade_type}, symbol='{self.symbol}', "
            f"entry={self.entry_price}, P&L={pnl_str}, status={self.status})"
        )

    def is_open(self) -> bool:
        """Check if trade is still open."""
        return self.status == "OPEN"

    def is_closed(self) -> bool:
        """Check if trade has closed."""
        return self.status == "CLOSED"

    def is_profitable(self) -> bool:
        """Check if trade made a profit."""
        return self.profit_loss is not None and self.profit_loss > 0


class PerformanceMetrics(Base):
    """
    Daily and period-based performance metrics for strategies.
    
    Tracks cumulative statistics: win rate, profit factor, Sharpe ratio, etc.
    Updated after each trade closes.
    """
    __tablename__ = "performance_metrics"

    id = Column(Integer, primary_key=True, index=True)
    
    # Period
    date = Column(DateTime, nullable=False, index=True, unique=True)
    
    # Trade Statistics
    total_trades = Column(Integer, default=0)
    winning_trades = Column(Integer, default=0)
    losing_trades = Column(Integer, default=0)
    win_rate = Column(Float, nullable=True)  # % of profitable trades
    
    # Financial Metrics
    total_profit_loss = Column(Float, default=0.0)  # Total P&L
    gross_profit = Column(Float, default=0.0)  # Sum of wins
    gross_loss = Column(Float, default=0.0)  # Sum of losses
    profit_factor = Column(Float, nullable=True)  # Gross Profit / Gross Loss
    
    # Risk Metrics
    largest_win = Column(Float, nullable=True)
    largest_loss = Column(Float, nullable=True)
    average_win = Column(Float, nullable=True)
    average_loss = Column(Float, nullable=True)
    
    # Risk-Adjusted Returns
    sharpe_ratio = Column(Float, nullable=True)  # Return / Risk
    sortino_ratio = Column(Float, nullable=True)  # Return / Downside Risk
    max_drawdown = Column(Float, nullable=True)  # Max cumulative loss %
    
    # Account Statistics
    account_balance = Column(Float, nullable=True)  # End-of-period balance
    daily_return_percent = Column(Float, nullable=True)  # Day's return %
    
    date_created = Column(DateTime, default=datetime.utcnow)
    date_modified = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    # Indices
    __table_args__ = (
        Index('idx_metrics_date', 'date'),
    )

    def __repr__(self) -> str:
        return (
            f"PerformanceMetrics(date={self.date.date()}, "
            f"trades={self.total_trades}, win_rate={self.win_rate:.1%}, "
            f"P&L={self.total_profit_loss:.2f})"
        )
